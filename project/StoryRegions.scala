import sbt.*

/**
  * Extracts the `// #region <id>` ... `// #endregion` blocks of the ui-gallery's story sources into
  * a generated Scala object, so the gallery's code panel shows exactly the code the story runs.
  * Each block is dedented, and keeps its file and line range for a link to GitHub.
  */
object StoryRegions:
  private val Start = """^\s*// #region (\S+)\s*$""".r
  private val End   = """^\s*// #endregion\s*$""".r

  case class Region(id: String, file: String, startLine: Int, endLine: Int, code: String)

  /** The regions of one source file; `file` is the path shown in links. */
  def parse(lines: Seq[String], file: String): Seq[Region] =
    val regions                     = Seq.newBuilder[Region]
    var open: Option[(String, Int)] = None
    lines
      .zipWithIndex
      .foreach { (line, i) =>
        (line, open) match
          case (Start(id), None) =>
            open = Some((id, i + 1))
          case (Start(id), Some((outer, _))) =>
            sys.error(s"${file}:${i + 1}: region ${id} starts inside region ${outer}")
          case (End(), Some((id, start))) =>
            val body = lines.slice(start, i)
            regions += Region(id, file, start + 1, i, dedent(body).mkString("\n"))
            open = None
          case (End(), None) =>
            sys.error(s"${file}:${i + 1}: #endregion without #region")
          case _ =>
      }
    open.foreach((id, start) => sys.error(s"${file}:${start}: region ${id} is never closed"))
    regions.result()

  private def dedent(body: Seq[String]): Seq[String] =
    val trimmed = body.dropWhile(_.trim.isEmpty).reverse.dropWhile(_.trim.isEmpty).reverse
    val indent  = trimmed.filter(_.trim.nonEmpty).map(_.takeWhile(_ == ' ').length).minOption
    trimmed.map(l => l.drop(indent.getOrElse(0)))

  private def literal(s: String): String =
    val sb = StringBuilder("\"")
    s.foreach {
      case '"' =>
        sb.append("\\\"")
      case '\\' =>
        sb.append("\\\\")
      case '\n' =>
        sb.append("\\n")
      case c =>
        sb.append(c)
    }
    sb.append('"').toString

  /**
    * Write `<pkg>/StorySources.scala` under `outDir` from the `.scala` files under `sourceDir`.
    * `repoBase` makes the recorded file paths relative to the repository root.
    */
  def generate(sourceDir: File, repoBase: File, outDir: File, pkg: String): Seq[File] =
    val files   = (sourceDir ** "*.scala").get().sortBy(_.getPath)
    val regions = files.flatMap { f =>
      val rel = IO.relativize(repoBase, f).getOrElse(f.getPath)
      parse(IO.readLines(f), rel)
    }
    regions
      .groupBy(_.id)
      .collect {
        case (id, rs) if rs.size > 1 =>
          sys.error(s"region ${id} is defined more than once: ${rs.map(_.file).mkString(", ")}")
      }
    val entries = regions.map { r =>
      val source =
        s"StorySource(${literal(r.code)}, ${literal(r.file)}, ${r.startLine}, ${r.endLine})"
      s"    ${literal(r.id)} -> ${source}"
    }
    val src =
      s"""package ${pkg}
         |
         |// Generated by project/StoryRegions.scala from the `// #region` blocks of the stories
         |object StorySources:
         |  val all: Map[String, StorySource] = Map(
         |${entries.mkString(",\n")}
         |  )
         |""".stripMargin
    val out = outDir / pkg.replace('.', '/') / "StorySources.scala"
    IO.write(out, src)
    Seq(out)

end StoryRegions
