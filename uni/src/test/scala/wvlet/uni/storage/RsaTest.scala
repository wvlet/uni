  test("RFC 7515 A.2 RS256 signature") {
    val sig = Rsa.signSha256(rfcKey, signingInput.getBytes("UTF-8"))
    GoogleOAuth.base64Url(sig) shouldBe expectedSignature
  }

  test("signing twice gives the same signature despite blinding") {
    val a = Rsa.signSha256(rfcKey, "hello".getBytes("UTF-8"))
    val b = Rsa.signSha256(rfcKey, "hello".getBytes("UTF-8"))
    a.toSeq shouldBe b.toSeq
    Rsa.verifySha256(rfcKey.modulus, rfcKey.publicExponent, "hello".getBytes("UTF-8"), a) shouldBe
      true
    Rsa.verifySha256(rfcKey.modulus, rfcKey.publicExponent, "hellO".getBytes("UTF-8"), a) shouldBe
      false
  }

  test("toString hides the key") {
    rfcKey.toString shouldBe "RsaPrivateKey(2048 bits, ****)"
  }

  test("reject malformed PEM") {
    val e1 = intercept[StorageException] {
      Rsa.parsePem("not a key")
    }
    e1.code shouldBe StorageErrorCode.InvalidCredentials
    val e2 = intercept[StorageException] {
      Rsa.parsePem("-----BEGIN PRIVATE KEY-----\nMAA=\n-----END PRIVATE KEY-----")
    }
    e2.code shouldBe StorageErrorCode.InvalidCredentials
    val e3 = intercept[StorageException] {
      Rsa.parsePem("-----BEGIN PRIVATE KEY-----\nMIIBAAAA\n-----END PRIVATE KEY-----")
    }
    e3.code shouldBe StorageErrorCode.InvalidCredentials
