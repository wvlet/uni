#!/usr/bin/env python3
"""Generates BrotliTables.scala: the transform list (RFC 7932, Appendix B) and the literal context
lookup table (RFC 7932, section 7.1).

Usage: gen-brotli-tables.py <transform.c> <context.c>

Both files come from https://github.com/google/brotli (c/common/, MIT license), which stores the
RFC's tables in a compact form; this script expands them.
"""
import os
import re
import sys

transform_c = open(sys.argv[1]).read()
context_c = open(sys.argv[2]).read()


def c_string(body):
    # Concatenate the C string literals and decode their escapes
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
    s = "".join(parts)
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\":
            n = s[i + 1]
            if n in "01234567":
                m = re.match(r"[0-7]{1,3}", s[i + 1 :])
                out.append(int(m.group(0), 8))
                i += 1 + len(m.group(0))
                continue
            if n == "x":
                m = re.match(r"[0-9A-Fa-f]{1,2}", s[i + 2 :])
                out.append(int(m.group(0), 16))
                i += 2 + len(m.group(0))
                continue
            out.append({"n": 10, "t": 9, "\\": 92, '"': 34, "'": 39}[n])
            i += 2
            continue
        out.append(ord(c))
        i += 1
    return bytes(out)


prefix_suffix = c_string(re.search(r"kPrefixSuffix\[\d+\] =(.*?);", transform_c, re.S).group(1)) + b"\0"  # the implicit trailing zero
ps_map = [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", re.search(r"kPrefixSuffixMap\[\d+\] = \{(.*?)\}", transform_c, re.S).group(1))]
types = {
    "IDENTITY": 0, "UPPERCASE_FIRST": 10, "UPPERCASE_ALL": 11,
    **{f"OMIT_LAST_{i}": i for i in range(1, 10)},
    **{f"OMIT_FIRST_{i}": 11 + i for i in range(1, 10)},
}
data = re.search(r"kTransformsData\[\] = \{(.*?)\};", transform_c, re.S).group(1)
data = re.sub(r"/\*.*?\*/", "", data, flags=re.S)
tokens = [t.strip() for t in data.split(",") if t.strip()]
values = [types[t.replace("BROTLI_TRANSFORM_", "")] if t.startswith("BROTLI") else int(t) for t in tokens]
transforms = [values[i : i + 3] for i in range(0, len(values), 3)]
assert len(transforms) == 121, len(transforms)


def ps(i):
    off = ps_map[i]
    n = prefix_suffix[off]
    return prefix_suffix[off + 1 : off + 1 + n]


def lit(b):
    return '"' + "".join(f"\\u{c:04x}" if c < 32 or c > 126 or c in (34, 92) else chr(c) for c in b) + '"'


lut = [int(x) for x in re.findall(r"\b\d+\b", re.sub(r"/\*.*?\*/", "", re.search(r"_kBrotliContextLookupTable\[2048\] = \{(.*?)\};", context_c, re.S).group(1), flags=re.S))]
assert len(lut) == 2048, len(lut)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "scala", "wvlet", "uni", "parquet", "codec", "BrotliTables.scala")
with open(out, "w") as f:
    f.write("package wvlet.uni.parquet.codec\n\n")
    f.write("// Generated by scripts/gen-brotli-tables.py. Do not edit.\n")
    f.write("private[codec] object BrotliTables:\n")
    f.write("  // Transforms (RFC 7932, Appendix B): prefix, type, suffix. Strings hold one byte per char.\n")
    f.write("  // Types: 0 identity, 1-9 omit last n, 10 uppercase first, 11 uppercase all, 12-20 omit first n - 11\n")
    f.write("  val prefixes: Array[String] = Array(\n")
    f.write(",\n".join(f"    {lit(ps(t[0]))}" for t in transforms))
    f.write("\n  )\n\n")
    f.write("  val types: Array[Int] = Array(\n")
    f.write(",\n".join(f"    {t[1]}" for t in transforms))
    f.write("\n  )\n\n")
    f.write("  val suffixes: Array[String] = Array(\n")
    f.write(",\n".join(f"    {lit(ps(t[2]))}" for t in transforms))
    f.write("\n  )\n\n")
    f.write("  // Literal context lookup (RFC 7932, section 7.1): for mode m, the context is\n")
    f.write("  // contextLookup(512 * m + p1) | contextLookup(512 * m + 256 + p2)\n")
    f.write("  val contextLookup: Array[Byte] = Array[Byte](\n")
    rows = [", ".join(str(v) for v in lut[i : i + 16]) for i in range(0, 2048, 16)]
    f.write(",\n".join(f"    {r}" for r in rows))
    f.write("\n  )\n")
print(out)
