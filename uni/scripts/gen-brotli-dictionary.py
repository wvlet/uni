#!/usr/bin/env python3
"""Generates BrotliDictionary.scala from the Brotli static dictionary (RFC 7932, Appendix A).

Usage: gen-brotli-dictionary.py <dictionary.bin>

dictionary.bin comes from https://github.com/google/brotli (c/common/dictionary.bin, MIT license).
The source embeds it gzip-compressed and base64-encoded; Inflate expands it on first use.
"""
import base64
import gzip
import hashlib
import os
import sys

SHA256 = "20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70"

data = open(sys.argv[1], "rb").read()
assert len(data) == 122784, len(data)
assert hashlib.sha256(data).hexdigest() == SHA256
encoded = base64.b64encode(gzip.compress(data, 9, mtime=0)).decode("ascii")
chunks = [encoded[i : i + 100] for i in range(0, len(encoded), 100)]
# Keep each string literal well under the JVM's 64 KiB constant limit
groups = [chunks[i : i + 400] for i in range(0, len(chunks), 400)]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "scala", "wvlet", "uni", "parquet", "codec", "BrotliDictionary.scala")
with open(out, "w") as f:
    f.write("package wvlet.uni.cloud.parquet.codec\n\n")
    f.write("// Generated by scripts/gen-brotli-dictionary.py. Do not edit.\n")
    f.write("// The Brotli static dictionary (RFC 7932, Appendix A), gzip-compressed and base64-encoded.\n")
    f.write(f"// SHA-256 of the dictionary: {SHA256}\n")
    f.write("private[codec] object BrotliDictionary:\n")
    f.write("  final val Size = 122784\n\n")
    for gi, g in enumerate(groups):
        f.write(f"  private def part{gi}: String =\n")
        f.write("    Seq(\n")
        f.write(",\n".join(f'      "{c}"' for c in g))
        f.write("\n    ).mkString\n\n")
    f.write("  lazy val data: Array[Byte] =\n")
    f.write("    val gz = java.util.Base64.getDecoder.decode(" + " + ".join(f"part{i}" for i in range(len(groups))) + ")\n")
    f.write("    val d  = Inflate.gunzip(gz, Size)\n")
    f.write("    if d.length != Size then\n")
    f.write('      throw IllegalStateException("The Brotli dictionary is damaged")\n')
    f.write("    d\n")
print(out, len(encoded))
